#include "terminal.h"

extern volatile uint32_t *framebuffer_ptr;
extern volatile uint64_t framebuffer_pitch;
extern volatile uint64_t framebuffer_height;
extern volatile uint64_t framebuffer_width;

uint64_t terminal_x = 0;
uint64_t terminal_y = 0;

static volatile int terminal_lock = 0;

static void lock_terminal() {
    while (__sync_lock_test_and_set(&terminal_lock, 1)) {
        asm volatile("pause");
    }
}

static void unlock_terminal() {
    __sync_lock_release(&terminal_lock);
}

#define FONT_HEIGHT 16
#define FONT_WIDTH 8

void clear_screen() {
    lock_terminal();
	for(uint64_t y = 0; y < framebuffer_height; y++) {
		for(uint64_t x = 0; x < framebuffer_width; x++) {
			framebuffer_ptr[y * (framebuffer_pitch / 4) + x] = 0x0;
		}
	}
	terminal_x = 0;
	terminal_y = 0;
    unlock_terminal();
}

void terminal_scroll() {
	uint32_t* dst = framebuffer_ptr;
	uint32_t* src = framebuffer_ptr + (framebuffer_pitch/4)*FONT_HEIGHT;
	uint64_t copy_size = (framebuffer_height - FONT_HEIGHT) * framebuffer_pitch;

	memmove(dst, src, copy_size);
	uint32_t* last_line = framebuffer_ptr + (framebuffer_height - FONT_HEIGHT)*(framebuffer_pitch/4);
		for (uint64_t y = 0; y < FONT_HEIGHT; y++)
    			for (uint64_t x = 0; x < framebuffer_width; x++)
        		last_line[y*(framebuffer_pitch/4) + x] = 0x00000000;
	terminal_y -= FONT_HEIGHT;

}

static void write_terminal_unlocked(char c) {
    if(c == '\n') {
        terminal_x = 0;
        terminal_y += FONT_HEIGHT;
    }
    else if(c == '\b') {
        if(terminal_x > 0) {
            terminal_x -= FONT_WIDTH;
            for(uint8_t y = 0; y < FONT_HEIGHT; y++) {
				for(uint8_t x = 0; x < FONT_WIDTH; x++) {
					framebuffer_ptr[(y + terminal_y) * (framebuffer_pitch / 4) + (x + terminal_x)] = 0x0;
				}
			}
        }
    }
	else {
		for(uint8_t y = 0; y < FONT_HEIGHT; y++) {
			uint8_t line = font8x16[c][y];
			for(uint8_t x = 0; x < FONT_WIDTH; x++) {
				uint8_t mask = 0x80 >> x;
					if(line & mask) {
						framebuffer_ptr[(y + terminal_y) * (framebuffer_pitch / 4) + (x + terminal_x)] = 0xFFFFFFFF;
				}
			}
		}
		terminal_x += FONT_WIDTH;
	}
	if(terminal_x >= framebuffer_width) {
		terminal_x = 0;
		terminal_y += FONT_HEIGHT;
	}
	if(terminal_y >= framebuffer_height) {
		terminal_scroll();
	}
}

void write_terminal(char c) {
    lock_terminal();
    write_terminal_unlocked(c);
    unlock_terminal();
}

static void print_str_unlocked(char *str) {
	while(*str && *str != '\0') {
		write_terminal_unlocked(*str);
		str++;
	}
}

void print_str(char *str) {
    lock_terminal();
    print_str_unlocked(str);
    unlock_terminal();
}

static void print_uint_unlocked(uint64_t val) {
    if (val / 10) {
        print_uint_unlocked(val / 10);
    }
    char c = (char)((val % 10) + '0');
    write_terminal_unlocked(c);
}

void print_uint(uint64_t val) {
    lock_terminal();
    print_uint_unlocked(val);
    unlock_terminal();
}

static void print_int_unlocked(int64_t val) {
    if (val < 0) {
        write_terminal_unlocked('-');
        val = -val;
    }
    print_uint_unlocked((uint64_t)val);
}

void print_int(int64_t val) {
    lock_terminal();
    print_int_unlocked(val);
    unlock_terminal();
}

